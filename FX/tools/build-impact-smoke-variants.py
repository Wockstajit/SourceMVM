#!/usr/bin/env python3
"""Build Insurgency impact variants whose flying debris smoke ribbons are disabled.

The runtime strips ribbons on four of ten impact sequence slots and keeps the normal
variant on six, doubling the former 30% keep rate. Povarhok's short local impact puffs
are intentionally outside this transform. Particle burst counts are integers, so a
fractional keep rate belongs at the top-level impact creation.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path


SUFFIX = "_nosmoketrails"
MARKER = "// generated by build-impact-smoke-variants.py -- do not hand-edit"
EMPTY_SYSTEM = "particles/dev/empty.vpcf"

# These are the converted Insurgency components that draw the long white/grey flying
# ribbons seen in dense indoor gunfire.  Metal spark tracers are intentionally absent.
SMOKE_TRAIL_SYSTEMS = {
    "impact_concrete_burst",
    "impact_dirt_burst",
    "impact_dirt_burst_b",
    "impact_generic_debris_tracer",
    "impact_generic_debris_tracer_b",
    "impact_generic_dust_tracer",
    "impact_generic_dust_tracer_b",
}

RESOURCE_RE = re.compile(
    r'((?:m_ChildRef|m_hFallback)\s*=\s*resource:")([^"]+?)(\.vpcf")'
)


def _base_stem(resource: str) -> str:
    stem = Path(resource.replace("\\", "/")).stem
    if stem.endswith("_less"):
        stem = stem[:-5]
    return stem


def make_no_smoke_trails(text: str) -> str:
    """Rewrite a particle closure so smoke-ribbon children resolve to dev/empty."""

    def replace_ref(match: re.Match[str]) -> str:
        resource = match.group(2).replace("\\", "/")
        if not resource.startswith("particles/filmmaker/insurgency/impact_fx_ins/"):
            return match.group(0)
        if _base_stem(resource) in SMOKE_TRAIL_SYSTEMS:
            return match.group(1) + EMPTY_SYSTEM[:-5] + match.group(3)
        if resource.endswith(SUFFIX):
            return match.group(0)
        return match.group(1) + resource + SUFFIX + match.group(3)

    rewritten = RESOURCE_RE.sub(replace_ref, text)
    rewritten = rewritten.replace(MARKER + "\n", "").rstrip("\n")
    return rewritten + "\n" + MARKER + "\n"


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--content-root", type=Path, required=True)
    parser.add_argument("--dry-run", action="store_true")
    return parser.parse_args()


def main() -> int:
    args = parse_args()
    root = args.content_root.resolve()
    impact_dirs = [
        root / "particles" / "filmmaker" / "insurgency" / "impact_fx_ins",
    ]
    impact_dirs = [path for path in impact_dirs if path.is_dir()]
    if not impact_dirs:
        print(f"impact directories not found under: {root}")
        return 1

    sources = sorted(
        path for impact_dir in impact_dirs for path in impact_dir.glob("*.vpcf")
        if not path.stem.endswith(SUFFIX)
    )
    for path in sources:
        output = path.with_name(path.stem + SUFFIX + path.suffix)
        if not args.dry_run:
            output.write_text(
                make_no_smoke_trails(path.read_text(encoding="utf-8")),
                encoding="utf-8",
            )

    print(f"{len(sources)} impact particle(s) -> {len(sources)} smoke-trail-free variant(s)"
          + (" (dry run)" if args.dry_run else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
