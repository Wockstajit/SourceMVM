#!/usr/bin/env python3
"""Generate the "Less" variant of each On particle: 30% smaller, fading 30% faster.

WHAT "LESS" MEANS (decided by the user, 2026-09-02)
    "Less is the same as On. It's just that everything is thirty percent smaller and fades thirty
    percent faster, because it's less."

    So Less is a TRANSFORM of the On asset, not a different asset. That is a change of shape from
    what shipped before: each Less-capable category used to point at a DIFFERENT Insurgency system
    (HE Less -> ins_m203_explosion), which is why Less read as another effect rather than a smaller
    version of the same one.

WHY ITS OWN SCRIPT
    This is a new capability, so it gets its own entry point rather than being bolted onto
    convert-fx-source1.ps1 or postprocess_insurgency.py. It reads an On .vpcf and writes
    <name>_less.vpcf beside it; it never edits the On asset, and it can be re-run safely.

WHAT IT SCALES, AND WHAT IT DELIBERATELY DOES NOT
    SIZE x0.70
      m_flRadiusMin / m_flRadiusMax   the particle's world radius (C_INIT_RandomRadius)
      m_flStartScale / m_flEndScale   scale-over-lifetime endpoints
    FADE 30% FASTER  (a shorter life IS a faster fade for a puff; the sprite still fades over its
    own curve, that curve just runs out sooner)
      m_fLifetimeMin / m_fLifetimeMax
      m_flStartFadeOutTime            so the fade begins proportionally earlier, not later

    NOT touched, on purpose:
      m_flMaxSize            reads as a normalised/screen-space renderer cap (0.9), not a world
                             size -- scaling it would clamp the sprite, not shrink the effect.
      m_flFadeStartTime /
      m_flFadeEndTime        these are the fade-IN window on C_OP_FadeIn. Shrinking them makes the
                             particle APPEAR faster, which is not what "fades faster" asked for.
      velocities / speeds    "smaller" is not "slower"; the spark-speed pass in
                             postprocess_insurgency.py already owns launch velocity.

    The split above is the reviewable part of this tool. If a Less variant looks wrong in game, the
    fix is to move a field between these lists -- with a comment saying what was observed -- not to
    add a blanket "scale every float" rule.

USAGE
    python FX/tools/build-less-variants.py --content-root <content/source_mvm_fx> --dry-run
    python FX/tools/build-less-variants.py --content-root <content/source_mvm_fx> \\
        --only particles/filmmaker/insurgency/explosion_fx_ins/ins_grenade_explosion.vpcf

A generated file carries LESS_MARKER so a re-run overwrites it rather than scaling it again.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

SIZE_SCALE = 0.70
FADE_SCALE = 0.70

# m_flMinLength/m_flMaxLength are the extent of a C_OP_RenderTrails streak, and they ARE size.
# Leaving them out (as this list originally did) left every trail at full length while the rest of
# the effect shrank, so a "smaller" explosion still threw full-length streaks across the room --
# visible in Less and On alike, reported from screenshots 2026-09-02.
SIZE_FIELDS = ("m_flRadiusMin", "m_flRadiusMax", "m_flStartScale", "m_flEndScale",
               "m_flMinLength", "m_flMaxLength")
FADE_FIELDS = ("m_fLifetimeMin", "m_fLifetimeMax", "m_flStartFadeOutTime")

# HOW MANY PARTICLES, not just how big and how long.
#
# User definition 2026-09-02: "less is the same thing as on -- their time is reduced by thirty,
# particle amount reduced by thirty, size reduced by thirty." Size and time were already handled;
# COUNT was not, so a Less impact threw exactly as many chunks as On, just smaller and shorter.
#
#   m_nParticlesToEmit  C_OP_InstantaneousEmitter's burst size -- the one that matters for an
#                       impact, which is a single burst (116 of these across the impact pack).
#   m_flEmitRate        C_OP_ContinuousEmitter's per-second rate, for the few systems that stream.
#   m_nMaxParticles     the system's own ceiling. Scaled too, or it would sit above the reduced
#                       burst and stop meaning anything; kept >= 1 so a system never emits nothing.
#
# These are integers, so they round rather than truncate: 15 -> 11 (10.5), not 10. A count of 1
# stays 1 -- rounding it to 0 would delete the effect instead of reducing it.
COUNT_SCALE = 0.70
COUNT_FIELDS_INT = ("m_nParticlesToEmit", "m_nMaxParticles")
COUNT_FIELDS_FLOAT = ("m_flEmitRate",)

LESS_MARKER = "// generated by build-less-variants.py -- do not hand-edit"
LESS_SUFFIX = "_less"


def _scale_fields(text: str, fields: tuple[str, ...], factor: float) -> tuple[str, int]:
    """Multiply every `field = <number>` assignment by factor. Returns (text, count)."""
    hits = 0

    def repl(m: "re.Match[str]") -> str:
        nonlocal hits
        hits += 1
        value = float(m.group(2)) * factor
        # Keep it readable: particle authors write 50.0, not 34.99999999999999.
        return "%s%s" % (m.group(1), ("%.4f" % value).rstrip("0").rstrip(".") or "0")

    for field in fields:
        pattern = re.compile(r"(" + re.escape(field) + r"\s*=\s*)(-?\d+(?:\.\d+)?)")
        text = pattern.sub(repl, text)
    return text, hits


def _scale_int_fields(text: str, fields: tuple[str, ...], factor: float) -> tuple[str, int]:
    """Scale integer count fields, rounding rather than truncating and never reaching zero."""
    hits = 0

    def repl(m: "re.Match[str]") -> str:
        nonlocal hits
        original = int(m.group(2))
        scaled = max(1, int(round(original * factor))) if original > 0 else original
        if scaled == original:
            return m.group(0)
        hits += 1
        return "%s%d" % (m.group(1), scaled)

    for field in fields:
        pattern = re.compile(r"(" + re.escape(field) + r"\s*=\s*)(\d+)")
        text = pattern.sub(repl, text)
    return text, hits


def make_less(text: str) -> tuple[str, int, int]:
    """Return (less_text, size_hits, fade_hits) for one On particle's source."""
    text, size_hits = _scale_fields(text, SIZE_FIELDS, SIZE_SCALE)
    text, fade_hits = _scale_fields(text, FADE_FIELDS, FADE_SCALE)
    text, _ = _scale_int_fields(text, COUNT_FIELDS_INT, COUNT_SCALE)
    text, _ = _scale_fields(text, COUNT_FIELDS_FLOAT, COUNT_SCALE)

    # Child references must point at the children's OWN Less variants, or a "smaller" explosion
    # would still spawn full-size smoke. The children are generated in the same pass.
    #
    # m_hFallback too. It is the system CS2 substitutes when this one is over budget, so a Less
    # variant whose fallback is the On original would silently jump back to full size under load.
    # Found by FX/tools/verify-fx-scaling.py: 29 On/Less pairs differed on exactly this line and
    # nothing else.
    text = re.sub(
        r'((?:m_ChildRef|m_hFallback)\s*=\s*resource:")([^"]+?)(?<!' + LESS_SUFFIX + r')(\.vpcf")',
        lambda m: m.group(1) + m.group(2) + LESS_SUFFIX + m.group(3),
        text,
    )
    if LESS_MARKER not in text:
        text = text.rstrip("\n") + "\n" + LESS_MARKER + "\n"
    return text, size_hits, fade_hits


def closure(root: Path, start: Path) -> list[Path]:
    """`start` plus every .vpcf it reaches through m_ChildRef, so a whole effect is converted."""
    seen: list[Path] = []
    queue = [start]
    while queue:
        path = queue.pop()
        if path in seen or not path.is_file():
            continue
        seen.append(path)
        text = path.read_text(encoding="utf-8", errors="replace")
        # Follow fallbacks as well as children: the Less variant points at a _less fallback, so
        # that fallback must be generated too.
        for ref in re.findall(r'(?:m_ChildRef|m_hFallback)\s*=\s*resource:"([^"]+)"', text):
            child = root / ref
            if child.is_file():
                queue.append(child)
    return seen


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--content-root", type=Path, required=True,
                   help="content/source_mvm_fx (the tree holding authored .vpcf)")
    p.add_argument("--only", action="append", default=[],
                   help="content-relative .vpcf to convert (repeatable); default = every On target")
    p.add_argument("--subtree", default="particles/filmmaker",
                   help="content-relative folder to bake (default particles/filmmaker). Use this to "
                        "do one pack at a time, e.g. particles/filmmaker/insurgency -- the Modern "
                        "pack has its own mode and needs no Less variants.")
    p.add_argument("--dry-run", action="store_true", help="report, write nothing")
    return p.parse_args()


def main() -> int:
    args = parse_args()
    root = args.content_root.resolve()
    if not root.is_dir():
        print("content root not found: %s" % root)
        return 1

    starts = [root / rel for rel in args.only] if args.only else sorted(
        (root / args.subtree).rglob("*.vpcf"))
    starts = [p for p in starts if LESS_SUFFIX + ".vpcf" not in p.name]

    targets: list[Path] = []
    for start in starts:
        for path in closure(root, start):
            if path not in targets:
                targets.append(path)

    written = 0
    for path in targets:
        text = path.read_text(encoding="utf-8")
        less, size_hits, fade_hits = make_less(text)
        out = path.with_name(path.stem + LESS_SUFFIX + path.suffix)
        rel = out.relative_to(root).as_posix()
        if args.dry_run:
            print("%-72s size:%d fade:%d" % (rel, size_hits, fade_hits))
            continue
        out.write_text(less, encoding="utf-8")
        written += 1

    print("%d source particle(s) -> %d Less variant(s)%s"
          % (len(targets), len(targets) if args.dry_run else written,
             " (dry run, nothing written)" if args.dry_run else ""))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
