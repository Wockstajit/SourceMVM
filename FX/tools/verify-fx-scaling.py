#!/usr/bin/env python3
"""Prove the On and Less particle trees are scaled correctly, and that nothing was scaled by accident.

WHY THIS EXISTS
    The HE blast is shrunk into CS2 room scale by walking its child closure, and Less is a 0.7x
    transform of every On system. Both are applied in pieces, marker-guarded, and re-run across
    rebakes -- which is exactly how three kinds of fault hide:

      1. COLLATERAL: a child the HE blast shares with another effect gets shrunk along with it.
         This has happened (generic_nearglow, shared with the C4 and M203) and was only caught by
         hand. This tool finds every such case from the rules the hook actually swaps to.
      2. DOUBLE-SCALING: a multiplicative pass applied twice. A marker is supposed to prevent it;
         this checks each marker appears exactly once on every file it should, and never on a file
         it should not.
      3. LESS DRIFT: a Less variant that is not, in fact, "On with the size and fade fields at
         0.7x and nothing else different" -- a regenerated Less from a stale On, a field the
         builder forgot (trail length was one), or a hand edit.

WHAT IT CHECKS
    * Every root the C++ rules can resolve to (parsed from ParticleFxRules.cpp, so a new rule is
      covered without touching this file), its full closure, and which of those files carry the
      HE scale marker. Any HE-scaled file reachable from a non-HE root is COLLATERAL.
    * Every On file in the HE closure carries the scale and length markers exactly once; no file
      outside the closure carries them (an orphan that was scaled then dropped is reported, not
      failed -- it is unreferenced).
    * For every On file with a _less sibling, anywhere in the Insurgency tree: after stripping
      marker lines and mapping child refs to their _less names, the two files differ ONLY on the
      size/fade fields, and on those every Less value is the On value x0.7.

USAGE
    python FX/tools/verify-fx-scaling.py --content-root build/fx/fx-source1import/source2/content/source_mvm_fx
Exit 1 on any failure, so a build script can gate on it.
"""

from __future__ import annotations

import argparse
import re
import sys
from collections import deque
from pathlib import Path

INS = "particles/filmmaker/insurgency"
HE_ROOT = INS + "/explosion_fx_ins/ins_grenade_explosion.vpcf"
HE_SCALE = 0.45
LESS_SCALE = 0.70

HE_SCALED_MARKER = "// mvm: HE blast scaled to CS2 room scale"
HE_LENGTH_MARKER = "// mvm: trail lengths scaled with the blast"
HE_GLOW_MARKER_PREFIX = "// mvm: HE flash cut by "
LESS_MARKER = "// generated by build-less-variants.py"

# Must match build-less-variants.py exactly; a field here and not there (or vice versa) is a bug
# the Less-drift check will surface as "field differs but is not a scaled field".
LESS_SIZE_FIELDS = ("m_flRadiusMin", "m_flRadiusMax", "m_flStartScale", "m_flEndScale",
                    "m_flMinLength", "m_flMaxLength")
LESS_FADE_FIELDS = ("m_fLifetimeMin", "m_fLifetimeMax", "m_flStartFadeOutTime")
# Count fields scale too (user definition: amount -30% as well as size and time). The integer
# ones round and never go below 1, so they are checked against that rule, not a raw 0.70x.
LESS_COUNT_INT = ("m_nParticlesToEmit", "m_nMaxParticles")
LESS_COUNT_FLOAT = ("m_flEmitRate",)
LESS_SCALED = set(LESS_SIZE_FIELDS + LESS_FADE_FIELDS + LESS_COUNT_INT + LESS_COUNT_FLOAT)

RESOURCE_RE = re.compile(r'resource:"([^"]+\.vpcf)"')
RULE_RE = re.compile(r'"([a-z0-9_]+)",\s*"([a-z0-9_]+)"')
FIELD_LINE_RE = re.compile(r"^\s*(m_[A-Za-z0-9_]+)\s*=\s*(-?[0-9]+(?:\.[0-9]+)?)\s*$")


def read(p: Path) -> str:
    return p.read_text(encoding="utf-8", errors="replace")


def children(root: Path, p: Path) -> list[str]:
    return [r.replace("\\", "/") for r in RESOURCE_RE.findall(read(p))]


def closure(root: Path, start: str) -> set[str]:
    seen: set[str] = set()
    q = deque([start])
    while q:
        r = q.popleft()
        if r in seen:
            continue
        seen.add(r)
        p = root / r
        if p.is_file():
            q.extend(children(root, p))
    return seen


def rule_roots(rules_cpp: Path) -> set[str]:
    """Every '<pack>/<name>' an FXRULE macro names, as a content-relative On resource."""
    packs = ("explosion_fx_ins", "impact_fx_ins", "weapon_fx_ins", "weapon_fx_ins_b",
             "weapon_fx_tracers", "blood_fx", "blood_impact", "fire_01_ins", "ins_burning_fx",
             "ins_smokegrenade", "water_impact")
    out = set()
    for pack, name in RULE_RE.findall(read(rules_cpp)):
        if pack in packs:
            out.add("%s/%s/%s.vpcf" % (INS, pack, name))
    return out


def check_collateral(root: Path, roots: set[str], he_scaled: set[str]) -> list[str]:
    problems = []
    he_closure = closure(root, HE_ROOT)
    for r in sorted(roots):
        if r == HE_ROOT:
            continue
        other = closure(root, r)
        hit = sorted((other & he_scaled) - {HE_ROOT})
        # A file inside the HE closure that another root also reaches was shrunk for both.
        for h in hit:
            problems.append("COLLATERAL  %s  is HE-scaled but also reached from  %s" % (h, r))
    return problems


def check_markers(root: Path, he_scaled: set[str]) -> tuple[list[str], list[str]]:
    problems, notes = [], []
    he_closure = {c for c in closure(root, HE_ROOT) if (root / c).is_file()}
    for c in sorted(he_closure):
        if c.endswith("_less.vpcf"):
            continue
        t = read(root / c)
        # A pure container (the HE root itself) has nothing to scale, so the pass never stamps
        # it. Requiring a marker there would be a false positive.
        if not any(re.search(r"\b%s\s*=" % f, t) for f in LESS_SIZE_FIELDS):
            continue
        n_scale = t.count(HE_SCALED_MARKER)
        n_len = t.count(HE_LENGTH_MARKER)
        if n_scale != 1:
            problems.append("MARKER      %s  scale marker x%d (want 1)" % (c, n_scale))
        if n_len != 1:
            problems.append("MARKER      %s  length marker x%d (want 1)" % (c, n_len))
        n_glow = len(re.findall(re.escape(HE_GLOW_MARKER_PREFIX), t))
        if n_glow > 1:
            problems.append("MARKER      %s  glow marker x%d (want <=1)" % (c, n_glow))
    for s in sorted(he_scaled - he_closure):
        notes.append("orphan      %s  carries the HE scale marker but is no longer in the HE tree "
                     "(dropped child; unreferenced, harmless)" % s)
    return problems, notes


def normalise(text: str, to_less: bool) -> list[str]:
    lines = []
    for ln in text.splitlines():
        s = ln.strip()
        if s.startswith("// mvm:") or s.startswith(LESS_MARKER):
            continue
        if to_less:
            ln = re.sub(r'resource:"([^"]+?)(?<!_less)\.vpcf"', r'resource:"\1_less.vpcf"', ln)
        lines.append(ln)
    return lines


def check_less(root: Path) -> tuple[list[str], int]:
    problems = []
    checked = 0
    for on in sorted((root / INS).rglob("*.vpcf")):
        if on.stem.endswith("_less"):
            continue
        less = on.with_name(on.stem + "_less.vpcf")
        rel = on.relative_to(root).as_posix()
        if not less.is_file():
            continue
        checked += 1
        a = normalise(read(on), to_less=True)
        b = normalise(read(less), to_less=False)
        if len(a) != len(b):
            problems.append("LESS        %s  line count differs from its Less (%d vs %d) -- "
                            "regenerate Less from this On" % (rel, len(a), len(b)))
            continue
        for la, lb in zip(a, b):
            if la == lb:
                continue
            ma, mb = FIELD_LINE_RE.match(la), FIELD_LINE_RE.match(lb)
            if not (ma and mb and ma.group(1) == mb.group(1)):
                problems.append("LESS        %s  differs on a non-scalar line:\n"
                                "              On:   %s\n              Less: %s"
                                % (rel, la.strip(), lb.strip()))
                continue
            field = ma.group(1)
            va, vb = float(ma.group(2)), float(mb.group(2))
            if field not in LESS_SCALED:
                problems.append("LESS        %s  %s differs (%g vs %g) but is NOT a scaled field"
                                % (rel, field, va, vb))
                continue
            if field in LESS_COUNT_INT:
                # build-less-variants rounds integer counts and floors them at 1.
                want = max(1, int(round(va * LESS_SCALE))) if va > 0 else va
                if abs(vb - want) > 0.5:
                    problems.append("LESS        %s  %s = %g, want %d (round(%g x %.2f), min 1)"
                                    % (rel, field, vb, want, va, LESS_SCALE))
                continue
            want = va * LESS_SCALE
            if abs(vb - want) > max(1e-3, abs(want) * 5e-3):
                problems.append("LESS        %s  %s = %g, want %g (On %g x %.2f)"
                                % (rel, field, vb, want, va, LESS_SCALE))
    return problems, checked


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--content-root", type=Path, required=True)
    ap.add_argument("--rules", type=Path,
                    default=Path("AfxHookSource2/Filmmaker/Movie/ParticleFxRules.cpp"))
    args = ap.parse_args()
    root = args.content_root.resolve()

    he_scaled = {p.relative_to(root).as_posix()
                 for p in (root / INS).rglob("*.vpcf")
                 if not p.stem.endswith("_less") and HE_SCALED_MARKER in read(p)}
    roots = rule_roots(args.rules)

    problems = []
    problems += check_collateral(root, roots, he_scaled)
    mk, notes = check_markers(root, he_scaled)
    problems += mk
    lp, n_less = check_less(root)
    problems += lp

    print("rule roots checked     : %d" % len(roots))
    print("HE-scaled On files     : %d" % len(he_scaled))
    # Say so loudly when the tree this tool guards is not reachable from any rule. Otherwise a
    # green result reads as "the HE blast is scaled correctly" when the HE blast is coming from
    # somewhere else entirely and these files are unreferenced leftovers.
    if HE_ROOT not in roots:
        print("  NOTE  %s is NOT a rule target any more -- the HE grenade resolves elsewhere\n"
              "        (Povarehok, since 2026-09-02). The %d scaled files below it are\n"
              "        unreferenced leftovers; the collateral check passes trivially for them."
              % (HE_ROOT, len(he_scaled)))
    print("On/Less pairs compared : %d" % n_less)
    for n in notes:
        print("  note  " + n)
    if problems:
        print("\n%d PROBLEM(S):" % len(problems))
        for p in problems:
            print("  " + p)
        return 1
    print("\nOK: no collateral scaling, every marker exactly once, every Less = On x %.2f on the "
          "size/fade fields and identical elsewhere." % LESS_SCALE)
    return 0


if __name__ == "__main__":
    sys.exit(main())
