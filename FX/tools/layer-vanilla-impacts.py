#!/usr/bin/env python3
"""Play CS2's own impact effect UNDERNEATH our ON-mode impact -- the RIGHT one for the surface.

Standalone on purpose: this is a new capability (compositing vanilla with the pack), not more of
what an existing converter pass does. Do not fold it into postprocess_insurgency.py's impact
passes (they own room-scale fit) or into tune-impact-sparks.py (spark readability).

WHAT THE USER ASKED FOR (2026-09-03)
    "Counter-Strike's default impact effect should continue playing normally, and our custom
     impact effects should be layered on top of it ... Keep our current impact system and its
     behavior, but stop it from replacing the base CS impact."
    and then: it has to be CS2's effect for the surface that was hit, on every hit.

HOW: ONE THIN WRAPPER PER (our target, CS2 surface) PAIR
CS2 has 45 impact surfaces; the pack has 24 systems to answer them with, so several surfaces
share one of ours (grass, mud, leaves and dirt all land on our dirt). A static child inside the
shared system can only name ONE vanilla effect, so the first version of this tool gave grass
CS2's dirt. This version generates a wrapper for every pair instead:

    particles/filmmaker/insurgency/impact_layered/impact_dirt_less__grass.vpcf
        children:  particles/impact_fx/impact_grass.vpcf        <- CS2's own, for THIS surface
                   particles/filmmaker/insurgency/impact_fx_ins/impact_dirt_less.vpcf   <- ours

and the hook (ParticleFxHook.cpp) rewrites its final impact target to the wrapper's name at
runtime via ImpactSurfaceLayeredTarget(): swap the target's directory for `impact_layered/`
and insert `__<surface>` before `.vpcf`. That naming is the CONTRACT between this file and
the C++; change one and you must change the other.

The wrappers live in their OWN directory so build-less-variants.py (which rewrites every
child ref to a _less sibling -- it would turn the vanilla ref into a nonexistent
particles/impact_fx/impact_grass_less.vpcf) and build-impact-smoke-variants.py never see
them. Wall surfaces use isolated donor closures with local smoke sprites enlarged 25%;
other surfaces reference the original systems. Run this after donor tuning so both inherit it.

WHICH TARGETS GET A WRAPPER: exactly the ones the hook can produce, mirrored from
ParticleFxHook.cpp / ParticleFxRules.cpp:
    Insurgency   <name>_less                 Impact On uses the Less slot internally
                 <name>_less_nosmoketrails   ImpactNoSmokeTrailTarget(), Insurgency only
    Povarehok    <hybrid>                    ImpactHybridTargetLower(); never gets _nosmoketrails
plus the plain <name> defensively. A wrapper for a target the hook never names is harmless.

WHY IT IS SAFE (measured, not assumed)
  * Child collections do NOT re-enter the swap hook -- after 9,334 creations with impacts ON,
    `mirv_filmmaker fx names` listed only vanilla top-level names and none of the pack's own
    children. So the vanilla child inside a wrapper is created, not swapped again.
  * Children inherit the parent's control points from the engine, so vanilla lands exactly
    where ours does. (A second engine-level create in the hook would NOT: the caller sets
    control points on the one collection pointer the create returns.)
  * Referencing a vanilla CS2 path from a pack .vpcf is proven: particles/dev/empty.vpcf is
    referenced 142 times and survives resourcecompiler.
  * PRECACHE: the vanilla impacts are CS2's stock effects, already precached by the game; the
    wrappers themselves are enumerated by the hook's warm-up alongside the targets they wrap.

SOURCE OF TRUTH is ParticleFxRules.cpp: both FXRULE_IMPACT and plain FXRULE rows inside
kVariantImpacts are parsed straight out of it, so the mapping cannot drift from the hook.

USAGE
    python FX/tools/layer-vanilla-impacts.py --content-root <.../content/source_mvm_fx> [--dry-run]
    python FX/tools/layer-vanilla-impacts.py --content-root ... --remove-static   # migration:
        strip the static vanilla children the first version glued into the shared systems.
        Run it BEFORE build-less-variants.py, or those refs get rewritten to *_less and break.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

from impact_wall_smoke import WallSmokeVariants

DEFAULT_RULES = Path("AfxHookSource2/Filmmaker/Movie/ParticleFxRules.cpp")

INS_DIR = "particles/filmmaker/insurgency/impact_fx_ins"
POV_DIR = "particles/filmmaker/povarehok/less/impacts/impact_fx"
LAYERED_DIRNAME = "impact_layered"           # the C++ side substitutes this for the last dir
SURFACE_SEP = "__"                           # ...and inserts SURFACE_SEP + surface before .vpcf

MARKER = "// generated by layer-vanilla-impacts.py -- do not hand-edit"
STATIC_MARKER = "// mvm: CS2's own impact plays underneath this one"   # the old first version
VANILLA_CHILD_RE = re.compile(
    r"\n?[ \t]*\{\s*m_ChildRef\s*=\s*resource:\"(particles/impact_fx/[^\"]+)\"\s*,?\s*\}\s*,?")


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--content-root", type=Path, required=True)
    parser.add_argument("--rules", type=Path, default=DEFAULT_RULES)
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--remove-static", action="store_true",
                        help="strip the first version's static vanilla children from the "
                             "shared systems (run before build-less-variants.py)")
    return parser.parse_args()


def impact_rows(rules_path: Path) -> list:
    """(vanilla match, insurgency name, povarehok hybrid name or None) for kVariantImpacts."""
    if not rules_path.is_file():
        raise SystemExit("rule table not found: %s" % rules_path)
    return impact_rows_text(rules_path.read_text(encoding="utf-8", errors="replace"))


def impact_rows_text(text: str) -> list:
    """Parse the shared rule table for generation and runtime-closure validation."""
    start = text.index("const VariantRule kVariantImpacts[] = {")
    block = text[start:text.index("\n};", start)]
    rows = []
    for kind, match, a, b in re.findall(
            r'FXRULE(_IMPACT)?\(\s*"([^"]+)"\s*,\s*"([^"]+)"\s*,\s*"([^"]+)"\s*\)', block):
        if kind:                      # FXRULE_IMPACT(match, insurgencyName, povarehokName)
            rows.append((match, a, b))
        elif a == "impact_fx_ins":    # FXRULE(match, pack, name): no hybrid
            rows.append((match, b, None))
    if not rows:
        raise SystemExit("no impact rows parsed (macro renamed?)")
    return rows


def surface_of(vanilla: str) -> str:
    """particles/impact_fx/impact_grass.vpcf -> grass. MUST match the C++ ImpactSurfaceOf()."""
    stem = vanilla.rsplit("/", 1)[-1]
    stem = stem[:-5] if stem.endswith(".vpcf") else stem
    return stem[7:] if stem.startswith("impact_") else stem


def layered_name(target: str, surface: str) -> str:
    """Mirror of the C++ ImpactSurfaceLayeredTarget()."""
    directory, name = target.rsplit("/", 1)
    parent = directory.rsplit("/", 1)[0]
    return "%s/%s/%s%s%s.vpcf" % (parent, LAYERED_DIRNAME, name[:-5], SURFACE_SEP, surface)


def wrapper_text(vanilla: str, target: str) -> str:
    return (
        '<!-- kv3 encoding:text:version{e21c7f3c-8a33-41c5-9977-a76d3a32aa0d} '
        'format:vpcf26:version{26288658-411e-4f14-b698-2e1e5d00dec6} -->\n'
        "{\n"
        "\tm_nBehaviorVersion = 8\n"
        '\t_class = "CParticleSystemDefinition"\n'
        "\tm_Children = \n"
        "\t[\n"
        "\t\t{\n"
        '\t\t\tm_ChildRef = resource:"%s"\n'
        "\t\t},\n"
        "\t\t{\n"
        '\t\t\tm_ChildRef = resource:"%s"\n'
        "\t\t},\n"
        "\t]\n"
        "\tm_bPreventnamebasedlookup = false\n"
        "\tm_nMaxParticles = 0\n"
        "}\n"
        "%s\n" % (vanilla, target, MARKER)
    )


def candidate_targets(ins_name: str, pov_name) -> list:
    out = [
        "%s/%s_less.vpcf" % (INS_DIR, ins_name),
        "%s/%s_less_nosmoketrails.vpcf" % (INS_DIR, ins_name),
        "%s/%s.vpcf" % (INS_DIR, ins_name),
    ]
    if pov_name:
        out.append("%s/%s.vpcf" % (POV_DIR, pov_name))
    return out


def remove_static(root: Path, dry_run: bool) -> int:
    """Migration: take the first version's static vanilla children back out."""
    stripped = 0
    for directory in (INS_DIR, POV_DIR):
        folder = root.joinpath(*directory.split("/"))
        if not folder.is_dir():
            continue
        for path in sorted(folder.glob("*.vpcf")):
            text = path.read_text(encoding="utf-8")
            if "particles/impact_fx/" not in text:
                continue
            out = VANILLA_CHILD_RE.sub("", text)
            out = out.replace("\n" + STATIC_MARKER + "\n", "\n").replace("\n" + STATIC_MARKER, "")
            if out == text:
                continue
            if not dry_run:
                path.write_text(out, encoding="utf-8")
            stripped += 1
    return stripped


def main() -> int:
    args = parse_args()
    root = args.content_root.resolve()

    if args.remove_static:
        n = remove_static(root, args.dry_run)
        print("Static vanilla children removed from %d shared system(s)." % n)
        return 0

    rows = impact_rows(args.rules)
    wall_smoke = WallSmokeVariants(root, args.dry_run)
    written = skipped = 0
    for vanilla, ins_name, pov_name in rows:
        surface = surface_of(vanilla)
        for target in candidate_targets(ins_name, pov_name):
            if not root.joinpath(*target.split("/")).is_file():
                skipped += 1
                continue
            wrapper = layered_name(target, surface)
            path = root.joinpath(*wrapper.split("/"))
            text = wrapper_text(vanilla, wall_smoke.target_for(target, surface))
            if path.is_file() and path.read_text(encoding="utf-8") == text:
                continue
            if not args.dry_run:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
            written += 1
            print("  %s" % wrapper)

    print("Vanilla-under-ours wrappers: %d written/updated for %d CS2 surfaces "
          "(%d candidate targets not present, skipped)." % (written, len(rows), skipped))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
