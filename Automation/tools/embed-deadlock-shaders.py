"""Embed Deadlock's D3D shaders into the hook as byte arrays.

WHY EMBED RATHER THAN LOAD FROM DISK
------------------------------------
The CS2 hook loads compiled shaders at runtime from `<HLAE>/resources/shaders`, resolving that
folder from its own module handle -- and the lookup is hardcoded to `AfxHookSource2.dll`
(hlaeFolder.cpp). The Deadlock hook is `AfxHookDeadlock.dll`, so that lookup returns nothing, the
path collapses to a relative one, and the shaders are not found. The Deadlock launcher also
injects straight out of the build tree rather than from an install prefix, so there is no staged
`resources/shaders` beside the DLL to find either.

Both problems disappear if the bytecode is simply in the DLL. Each group here comes to a few
kilobytes, the shaders never change independently of the C++ that uses them, and embedding removes
an entire class of "works until someone moves the DLL".

THE .acs CONTAINER
------------------
As parsed by AfxShaders.cpp:

    int32 version
    int32 indexSize
    indexSize * { int32 combo, int32 offset }     -- ascending by combo
    ... blobs ...

A combo's blob runs from its offset to the next combo's offset, or to end-of-file for the last.
Every shader here has a single combo (0), which the generated header asserts rather than assumes.

Run this when any of the source `.fxc` files change and have been rebuilt into `Shaders/build/`:

    py -3 Automation/tools/embed-deadlock-shaders.py
"""

from __future__ import annotations

import struct
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
BUILD = REPO / "Shaders" / "build"

# One entry per generated header: (output path, doc line describing what the group is for, shaders).
GROUPS = [
    (
        REPO / "AfxHookSource2" / "Deadlock" / "DeadlockBlitShaders.h",
        "The two compiled shaders the scaled-preview blit needs.",
        [
            ("kDeadlockBlitTriangleVs", "afx_blit_triangle_vs_5_0.acs", 0),
            ("kDeadlockBlitPs", "afx_blit_ps_5_0.acs", 0),
        ],
    ),
    (
        REPO / "AfxHookSource2" / "Deadlock" / "DeadlockOverlayShaders.h",
        "The compiled shaders the in-world overlay needs: the stroke pair (camera path, markers,"
        " target box) and the textured pair (key-number digits) --"
        " see AfxHookSource2/Deadlock/DeadlockOverlayDrawer.cpp.",
        [
            ("kDeadlockOverlayVs", "afx_deadlock_overlay_vs_5_0.acs", 0),
            ("kDeadlockOverlayPs", "afx_deadlock_overlay_ps_5_0.acs", 0),
            ("kDeadlockOverlayTexVs", "afx_deadlock_overlay_tex_vs_5_0.acs", 0),
            ("kDeadlockOverlayTexPs", "afx_deadlock_overlay_tex_ps_5_0.acs", 0),
        ],
    ),
]


def extract(path: Path, combo: int) -> bytes:
    data = path.read_bytes()
    if len(data) < 8:
        raise ValueError(f"{path.name}: too short to be an .acs")
    version, index_size = struct.unpack_from("<ii", data, 0)
    if index_size < 1:
        raise ValueError(f"{path.name}: empty combo index")

    entries = []
    for i in range(index_size):
        c, off = struct.unpack_from("<ii", data, 8 + i * 8)
        entries.append((c, off))

    for i, (c, off) in enumerate(entries):
        if c != combo:
            continue
        end = entries[i + 1][1] if i + 1 < index_size else len(data)
        blob = data[off:end]
        # Every Direct3D shader blob opens with this magic. Checking it means a container that
        # changed shape fails here, offline, instead of as a silent CreatePixelShader failure with
        # a preview that simply never draws.
        if blob[:4] != b"DXBC":
            raise ValueError(
                f"{path.name}: combo {combo} does not start with DXBC "
                f"(got {blob[:4]!r}) -- the container layout changed")
        return blob
    raise ValueError(f"{path.name}: combo {combo} not present")


def as_c_array(name: str, blob: bytes) -> str:
    lines = [f"const unsigned char {name}[] = {{"]
    for i in range(0, len(blob), 12):
        chunk = blob[i:i + 12]
        lines.append("\t" + " ".join(f"0x{b:02x}," for b in chunk))
    lines.append("};")
    lines.append(f"const unsigned int {name}Size = {len(blob)};")
    return "\n".join(lines)


def write_group(out_path: Path, doc_line: str, shaders: list) -> int:
    parts = [
        "#pragma once",
        "",
        "// AUTOGENERATED by Automation/tools/embed-deadlock-shaders.py -- do not edit.",
        "//",
        f"// {doc_line}",
        "//",
        "// The CS2 hook loads these from <HLAE>/resources/shaders at runtime, resolving that folder",
        "// from a module handle hardcoded to AfxHookSource2.dll. That lookup cannot work for",
        "// AfxHookDeadlock.dll, and the Deadlock launcher injects out of the build tree where no",
        "// staged resources folder exists either -- so the bytecode lives here instead. A few",
        "// kilobytes in the DLL costs nothing and removes a whole class of path and staging failure.",
        "",
        "namespace Deadlock {",
        "",
    ]
    for name, filename, combo in shaders:
        src = BUILD / filename
        if not src.exists():
            print(f"missing {src}")
            return 2
        blob = extract(src, combo)
        print(f"{filename}: combo {combo} -> {len(blob)} bytes")
        parts.append(f"// {filename}, combo {combo}")
        parts.append(as_c_array(name, blob))
        parts.append("")
    parts.append("} // namespace Deadlock")
    parts.append("")

    out_path.write_text("\n".join(parts), encoding="utf-8")
    print(f"wrote {out_path.relative_to(REPO)}")
    return 0


FONT_SRC = REPO / "Resources" / "resources" / "hexfont.tga"
FONT_OUT = REPO / "AfxHookSource2" / "Deadlock" / "DeadlockOverlayFont.h"


def write_font() -> int:
    """HLAE's hexfont (the digit atlas CS2's CampathDrawer draws key numbers from), embedded for the
    same reason as the shaders. The TGA is uncompressed 32-bit, top-left origin, and grayscale, so
    it is stored as luminance + alpha -- half the bytes -- and expanded back to RGBA at device time."""
    data = FONT_SRC.read_bytes()
    id_len, image_type = data[0], data[2]
    width, height = data[12] | data[13] << 8, data[14] | data[15] << 8
    bpp, flags = data[16], data[17]
    if image_type != 2 or bpp != 32 or not (flags & 0x20):
        print(f"{FONT_SRC.name}: expected uncompressed 32-bit top-left TGA "
              f"(type={image_type} bpp={bpp} flags=0x{flags:02x})")
        return 2
    pixels = data[18 + id_len:18 + id_len + width * height * 4]
    if len(pixels) != width * height * 4:
        print(f"{FONT_SRC.name}: truncated pixel data")
        return 2
    la = bytearray()
    for i in range(0, len(pixels), 4):
        b, g, r, a = pixels[i], pixels[i + 1], pixels[i + 2], pixels[i + 3]
        if not (r == g == b):
            print(f"{FONT_SRC.name}: texel {i // 4} is not grayscale; luminance+alpha would lose it")
            return 2
        la += bytes((r, a))
    parts = [
        "#pragma once",
        "",
        "// AUTOGENERATED by Automation/tools/embed-deadlock-shaders.py -- do not edit.",
        "//",
        "// HLAE's hexfont.tga: the 256x128 atlas of 8 x 2 glyph cells (0-F) CS2's CampathDrawer draws",
        "// camera-marker key numbers from. Stored as luminance + alpha per texel, top row first; see",
        "// AfxHookSource2/Deadlock/DeadlockOverlayDrawer.cpp for the expansion to RGBA.",
        "",
        "namespace Deadlock {",
        "",
        f"const unsigned int kDeadlockOverlayFontWidth = {width};",
        f"const unsigned int kDeadlockOverlayFontHeight = {height};",
        as_c_array("kDeadlockOverlayFontLA", bytes(la)),
        "",
        "} // namespace Deadlock",
        "",
    ]
    FONT_OUT.write_text("\n".join(parts), encoding="utf-8")
    print(f"{FONT_SRC.name}: {width}x{height} -> {len(la)} bytes")
    print(f"wrote {FONT_OUT.relative_to(REPO)}")
    return 0


def main() -> int:
    for out_path, doc_line, shaders in GROUPS:
        rc = write_group(out_path, doc_line, shaders)
        if rc != 0:
            return rc
    return write_font()


if __name__ == "__main__":
    raise SystemExit(main())
