// The float-range helpers are pure math, so they are evaluated for real (with stubs for the
// Panorama-only bits) rather than pattern-matched -- a tier list that silently goes wrong would
// otherwise still pass a source-shape assertion.
function wearMath() {
  const declaration = (marker, endMarker) => {
    const start = customizeSource.indexOf(marker);
    assert.notEqual(start, -1, `${marker} must exist`);
    return customizeSource.slice(start, customizeSource.indexOf(endMarker, start));
  };
  const helpers = [
    "wearCapDisabled",
    "wearRangeForSlot",
    "clampWearForSlot",
    "wearFracToValue",
    "wearValueToFrac",
    "wearTiersForSlot",
    "wearValue",
    "presetForWearValue",
    "defaultWearForSlot",
  ]
    .map((name) => {
      const start = customizeSource.indexOf(`function ${name}(`);
      const open = customizeSource.indexOf("{", start);
      let depth = 0;
      for (let index = open; index < customizeSource.length; index += 1) {
        if (customizeSource[index] === "{") depth += 1;
        if (customizeSource[index] === "}") {
          depth -= 1;
          if (depth === 0) return customizeSource.slice(start, index + 1);
        }
      }
      throw new Error(`${name} has no closing brace`);
    })
    .join("\n");
  return new Function(`
    function clamp01(x) { return x < 0 ? 0 : (x > 1 ? 1 : x); }
    function num(v) { return (typeof v === 'number' && isFinite(v)) ? v : 0; }
    var custSel = {}, CATALOG = {}, custWear = {};
    function selOpt(slot) { return CATALOG[slot] || null; }
    ${declaration("var WEAR_PRESETS = {", "var custWear = {")}
    ${helpers}
    return {
      set: function (meta, wear) { CATALOG.primary = ['label', 'value', meta]; custWear.primary = wear; },
      tiers: function () { return wearTiersForSlot('primary'); },
      range: function () { return wearRangeForSlot('primary'); },
      toValue: function (f) { return wearFracToValue('primary', f); },
      toFrac: function (v) { return wearValueToFrac('primary', v); },
      value: function () { return wearValue('primary'); },
      abbrev: WEAR_ABBREV,
    };
  `)();
}

test("the wear bar shows only the tiers a finish can reach, stretched across the whole bar", () => {
  const math = wearMath();
  const keys = () => math.tiers().map((tier) => tier.key).join(",");

  // AWP | Asiimov never ships below 0.18, so Factory New and Minimal Wear must not be drawn.
  math.set({ paint: 279, wearMin: 0.18, wearMax: 1.0 }, { preset: "custom", custom: 0.5 });
  assert.equal(keys(), "ft,ww,bs");
  assert.equal(math.tiers()[0].lo, 0.18, "the lowest visible tier starts at the cap, not at 0.15");

  // A 0.00-0.08 finish reaches Factory New and a sliver of Minimal Wear; together they must cover
  // the full bar instead of bunching up at the left edge.
  math.set({ paint: 37, wearMin: 0.0, wearMax: 0.08 }, { preset: "custom", custom: 0.0 });
  const range = math.range();
  const covered = math.tiers().reduce((sum, tier) => sum + (tier.hi - tier.lo), 0);
  assert.equal(keys(), "fn,mw");
  assert.ok(
    Math.abs(covered - (range.hi - range.lo)) < 1e-9,
    "the visible tiers must span the entire reachable range",
  );

  assert.deepEqual(math.abbrev, { fn: "FN", mw: "MW", ft: "FT", ww: "WW", bs: "BS" });
});

test("the wear slider's 0..1 maps onto the reachable range, and the cap toggle unlocks 0..1", () => {
  const math = wearMath();

  // Slider travel spans [wearMin, wearMax], so mid-track is the middle of what the skin allows.
  math.set({ paint: 417, wearMin: 0.0, wearMax: 0.08 }, { preset: "custom", custom: 0.04 });
  assert.ok(Math.abs(math.toValue(1) - 0.08) < 1e-9);
  assert.ok(Math.abs(math.toValue(0.5) - 0.04) < 1e-9);
  assert.ok(Math.abs(math.toFrac(0.04) - 0.5) < 1e-9);

  // A capped item clamps an out-of-range float; the same item uncapped keeps it and shows all five.
  math.set({ paint: 417, wearMin: 0.0, wearMax: 0.08 }, { preset: "custom", custom: 0.9 });
  assert.ok(Math.abs(math.value() - 0.08) < 1e-9);
  math.set({ paint: 417, wearMin: 0.0, wearMax: 0.08 }, { preset: "custom", custom: 0.9, noCap: true });
  assert.deepEqual([math.range().lo, math.range().hi], [0, 1]);
  assert.ok(Math.abs(math.value() - 0.9) < 1e-9);
  assert.equal(math.tiers().map((tier) => tier.key).join(","), "fn,mw,ft,ww,bs");

  // A degenerate cap intersects no tier under a strict test and must not leave the bar unlabelled.
  math.set({ paint: 10037, wearMin: 0.42, wearMax: 0.42 }, { preset: "custom", custom: 0.42 });
  assert.equal(math.tiers().length, 1);
  assert.equal(math.tiers()[0].key, "ww");
});

