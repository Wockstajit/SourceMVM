// Both cursor-pipe drag pumps hit-test EVERY registered slider themselves, because this HUD
// context gets no mouse-move events and the sliders are taken out of Panorama's own hit path
// while the pipe is live. So Panorama never gets the chance to reject an off-screen panel for
// them -- the pump has to do it.
//
// Asking only `panel.visible` is not enough and never was: nothing hides a slider ROW directly.
// A hidden tab page (applyTabs / applySvTabs / applyWrTabs), a collapsed card (its clipper) and a
// closed Advanced section all set the flag on a CONTAINER, and every row inside keeps
// `visible: true` plus the layout rectangle it had when it was last on screen. Every card lays
// its rows on the same grid at the same x, so a drag on the row you can see also drove whichever
// hidden row sat at the same y -- Smooth View's Breathing page vs its Tilt page, the CAMERA tab
// vs EFFECTS or RAGDOLLS, an open card vs a shut one behind it.
//
// This is invisible in review and only shows up in-game as two settings moving at once, so it is
// pinned here.
test("the drag pumps reject sliders whose ancestors are hidden, not just hidden sliders", () => {
  for (const [name, source, guard, hitTest] of [
    ["CONFIG", configWidgetsSource, "cfgPanelOnScreen", "cfgOverPanel"],
    ["Camera Editor", widgetsSource, "panelOnScreen", "overPanel"],
  ]) {
    const body = functionBody(source, guard);
    assert.match(body, /GetParent/,
      `${name}: ${guard} must walk the parent chain -- a row's own .visible stays true inside a hidden container`);
    assert.match(body, /if \(!\w+\.visible\) return false/,
      `${name}: ${guard} must reject an invisible panel anywhere in the chain`);
    // Failing open matters: this walk leaves our own tree and runs into CS2's native HUD panels.
    // A throw must fall back to the old behaviour, never leave every slider undraggable.
    assert.match(body, /catch \([^)]*\) \{ return true; \}/,
      `${name}: ${guard} must fail open so a property read that throws cannot kill the sliders`);
    assert.ok(functionBody(source, hitTest).includes(`${guard}(`),
      `${name}: ${hitTest} must consult ${guard} before accepting a press`);
  }
});
