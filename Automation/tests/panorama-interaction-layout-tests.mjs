// Regression guard. The S tokens are 8-digit '#rrggbbaa', so concatenating another alpha pair onto
// one builds an invalid 10-digit colour. Panorama throws on an invalid style value and the throw
// aborts the whole script -- appending '88' to S.accent for the search box border is what stopped the
// Customize modal from opening at all, because rebuild() runs on the first populateCustomize().
// hexAlpha() REPLACES the alpha byte and is the only correct way to restate one of these at a
// different opacity.
test("no S colour token is given a second alpha by string concatenation", () => {
  // Comments are stripped first, since the note documenting this trap quotes the broken form. The
  // `:` guard keeps 's2r://...' resource URLs (which are inside string literals) from being treated
  // as the start of a comment.
  const stripComments = (source) => source.split("\n").map((line) => {
    for (let i = 0; i < line.length - 1; i += 1) {
      if (line[i] === "/" && line[i + 1] === "/" && line[i - 1] !== ":") return line.slice(0, i);
    }
    return line;
  }).join("\n");
  const tokenNames = ["accent", "value", "dim", "label", "danger", "freeze", "render"];
  for (const source of [customizeSource, widgetsSource, customizePreviewSource]) {
    const code = stripComments(source);
    for (const name of tokenNames) {
      const bad = new RegExp(`S\\.${name}\\s*\\+\\s*'[0-9a-fA-F]{2}'`, "g");
      const hits = code.match(bad) || [];
      assert.deepStrictEqual(hits, [],
        `S.${name} already ends in an alpha byte -- use hexAlpha(S.${name}, 'aa') instead of ${hits[0]}`);
    }
  }
  // And the helper really does replace rather than append.
  const hexAlphaBody = functionBody(customizeSource, "hexAlpha");
  assert.match(hexAlphaBody, /c\.substring\(1, 7\)/, "hexAlpha must keep only rrggbb before the new alpha");
});

