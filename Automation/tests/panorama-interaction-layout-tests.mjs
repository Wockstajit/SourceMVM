// Scale-on-press is the ONE transform btnVisual may write, and it has to stay opt-in and symmetric.
// Opt-in because two callers already animate their own transform and a second writer would fight
// them: capBtn (capApply, CameraEditorCustomizeJs.h) and any segmented button handed to renderShake
// (CameraEditorRenderJs.h). Symmetric + centred because an off-centre or asymmetric press scale
// reads as the button sliding rather than being pushed.
test("scale-on-press is opt-in, centred, and the only transform a button painter writes", () => {
  const btnBody = functionBody(widgetsSource, "btnVisual");
  // Whole statement, not just the assignment: the opt-in gate is the `if` in front of it.
  const transforms = btnBody.match(/^.*\.style\.transform\s*=[^;]*;/gm) ?? [];
  assert.ok(transforms.length > 0, "btnVisual must drive the press scale");
  for (const line of transforms) {
    assert.match(line, /b\.__press/, "every transform write must be gated on the opt-in flag");
    assert.match(
      line,
      /scale3d\(0\.96,0\.96,1\)|scale3d\(1,1,1\)/,
      "the press scale is a symmetric 0.96, and it must reset to exactly 1",
    );
  }
  const interactiveBody = functionBody(widgetsSource, "interactive");
  assert.match(interactiveBody, /b\.__press\s*=\s*!!opts\.press/, "press must default to OFF");
  assert.match(interactiveBody, /transformOrigin\s*=\s*'50% 50%'/, "a press scale must be centred");
  // The two transform-owning callers must NOT be opted in, or they would fight btnVisual.
  const wearBody = functionBody(customizeSource, "wearSliderBlock");
  assert.ok(
    /capBtn\.style\.transform\s*=/.test(wearBody),
    "capBtn still animates its own transform (the pop)",
  );
  // The whole construction statement, not a paren-bounded slice: capBtn's onClick is itself a
  // function literal, so a `[^)]*` window stops at the first `)` inside it and can never see an
  // opt-in that follows.
  const capCtor = /var capBtn\s*=\s*btn\([\s\S]*?\);/.exec(wearBody);
  assert.ok(capCtor, "capBtn must be built with btn()");
  assert.doesNotMatch(
    capCtor[0],
    /press\s*:/,
    "capBtn owns style.transform (the pop), so it must not also opt into btnVisual's press scale",
  );
});

