const geometryProperty =
  /\.style\.(?:width|height|minWidth|maxWidth|minHeight|maxHeight|margin\w*|padding\w*|position|transform)\s*=/;
// The subset that actually REFLOWS: writing any of these from a hover/click painter resizes the
// control and shoves its siblings around. A centred, symmetric `transform` does not -- Panorama
// layout metrics are unaffected by a transform (see the CUST_SCALE note in CameraEditorCustomizeJs.h)
// -- so btnVisual is allowed exactly one, the opt-in scale-on-press, and nothing else.
const reflowProperty =
  /\.style\.(?:width|height|minWidth|maxWidth|minHeight|maxHeight|margin\w*|padding\w*|position)\s*=/;

function functionBody(source, name) {
  const signature = `function ${name}(`;
  const start = source.indexOf(signature);
  assert.notEqual(start, -1, `${name} must exist`);
  const open = source.indexOf("{", start);
  let depth = 0;
  for (let index = open; index < source.length; index += 1) {
    if (source[index] === "{") depth += 1;
    if (source[index] === "}") {
      depth -= 1;
      if (depth === 0) return source.slice(open + 1, index);
    }
  }
  throw new Error(`${name} has no closing brace`);
}

